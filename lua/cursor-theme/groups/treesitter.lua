local M = {}
local utils = require('cursor-theme.utils')

function M.get(colors, options)
    local c = colors
    local styles = options.styles
    local function styled(foreground, style)
        return vim.tbl_extend('force', { fg = foreground }, utils.style(style))
    end

    return {
        ['@variable'] = styled(c.variable, styles.variables),
        ['@variable.builtin'] = { fg = c.special },
        ['@variable.parameter'] = styled(c.variable, styles.variables),
        ['@variable.parameter.builtin'] = { fg = c.special },
        ['@variable.member'] = { fg = c.variable },
        ['@constant'] = { fg = c.constant },
        ['@constant.builtin'] = { fg = c.constant, bold = true },
        ['@constant.macro'] = { fg = c.special },
        ['@module'] = { fg = c.type },
        ['@module.builtin'] = { fg = c.type },
        ['@label'] = { fg = c.type },
        ['@string'] = { fg = c.string },
        ['@string.documentation'] = { fg = c.string },
        ['@string.escape'] = { fg = c.special, bold = true },
        ['@string.regexp'] = { fg = c.regex },
        ['@string.special'] = { fg = c.special },
        ['@string.special.symbol'] = { fg = c.constant },
        ['@string.special.url'] = { fg = c.accent, underline = true },
        ['@string.special.path'] = { fg = c.accent },
        ['@character'] = { fg = c.string },
        ['@character.special'] = { fg = c.special },
        ['@number'] = { fg = c.constant },
        ['@number.float'] = { fg = c.constant },
        ['@boolean'] = { fg = c.constant },
        ['@type'] = { fg = c.type },
        ['@type.builtin'] = { fg = c.type },
        ['@type.definition'] = { fg = c.type, bold = true },
        ['@type.qualifier'] = { fg = c.keyword },
        ['@attribute'] = { fg = c.special },
        ['@attribute.builtin'] = { fg = c.special },
        ['@property'] = { fg = c.variable },
        ['@function'] = styled(c.func, styles.functions),
        ['@function.builtin'] = { fg = c.func_builtin },
        ['@function.call'] = styled(c.func, styles.functions),
        ['@function.macro'] = { fg = c.special },
        ['@function.method'] = styled(c.func, styles.functions),
        ['@constructor'] = { fg = c.type },
        ['@operator'] = styled(c.operator, styles.operators),
        ['@keyword'] = styled(c.keyword, styles.keywords),
        ['@keyword.conditional'] = styled(c.keyword, styles.conditionals),
        ['@keyword.coroutine'] = { fg = c.keyword },
        ['@keyword.debug'] = { fg = c.error },
        ['@keyword.directive'] = { fg = c.special },
        ['@keyword.exception'] = { fg = c.keyword },
        ['@keyword.function'] = { fg = c.keyword },
        ['@keyword.import'] = { fg = c.keyword },
        ['@keyword.modifier'] = { fg = c.keyword },
        ['@keyword.operator'] = { fg = c.keyword },
        ['@keyword.repeat'] = { fg = c.keyword },
        ['@keyword.return'] = { fg = c.keyword },
        ['@keyword.type'] = { fg = c.keyword },
        ['@punctuation'] = { fg = c.fg_dim },
        ['@punctuation.bracket'] = { fg = c.punctuation },
        ['@punctuation.delimiter'] = { fg = c.punctuation },
        ['@punctuation.special'] = { fg = c.special },
        ['@comment'] = styled(c.comment, styles.comments),
        ['@comment.documentation'] = styled(c.comment, styles.comments),
        ['@comment.error'] = { fg = c.error },
        ['@comment.warning'] = { fg = c.warning },
        ['@comment.todo'] = { fg = c.accent },
        ['@comment.note'] = { fg = c.info },
        ['@markup.heading'] = { fg = c.accent, bold = true },
        ['@markup.heading.1'] = { fg = c.accent, bold = true },
        ['@markup.heading.2'] = { fg = c.accent, bold = true },
        ['@markup.heading.3'] = { fg = c.accent, bold = true },
        ['@markup.quote'] = { fg = c.fg_comment },
        ['@markup.math'] = { fg = c.accent },
        ['@markup.link'] = { fg = c.accent },
        ['@markup.link.label'] = { fg = c.accent, underline = true },
        ['@markup.link.url'] = { fg = c.accent, underline = true },
        ['@markup.raw'] = { fg = c.string },
        ['@markup.raw.block'] = { fg = c.fg, bg = c.bg_elevated },
        ['@markup.list'] = { fg = c.keyword },
        ['@markup.list.checked'] = { fg = c.ok },
        ['@markup.list.unchecked'] = { fg = c.fg_dim },
        ['@markup.strong'] = { bold = true },
        ['@markup.italic'] = { italic = true },
        ['@markup.strikethrough'] = { strikethrough = true },
        ['@tag'] = { fg = c.tag },
        ['@tag.builtin'] = { fg = c.tag },
        ['@tag.attribute'] = { fg = c.type },
        ['@tag.delimiter'] = { fg = c.fg_dim },
        ['@diff.plus'] = { fg = c.added },
        ['@diff.minus'] = { fg = c.deleted },
        ['@diff.delta'] = { fg = c.changed },
    }
end

return M
